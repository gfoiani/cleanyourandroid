"""Every list and example in the repo is usable and never names a protected package."""
import json

import pytest

import gen_tables
import guards
import listfile
import tweakfile
from helpers import ROOT, write

LISTS = sorted((ROOT / "lists").rglob("*.txt")) + sorted((ROOT / "examples").glob("*/debloat.txt"))
EXAMPLES = sorted(p for p in (ROOT / "examples").iterdir() if p.is_dir())


@pytest.mark.parametrize("path", LISTS, ids=lambda p: str(p.relative_to(ROOT)))
def test_list_parses_and_names_no_protected_package(path):
    parsed = listfile.load(path)

    assert parsed.entries, f"{path} has no packages"
    assert guards.protected([e.package for e in parsed.entries], guards.load()) == {}


def test_the_prompt_keeps_the_screen_awake_and_never_asks_to_lower_a_protection():
    prompt = (ROOT / "PROMPT.md").read_text(encoding="utf-8")

    assert prompt.count("Stay awake") >= 2, "turned on before the start and off again at the finish"
    assert "all black" in prompt                       # an asleep or locked screen is not damage
    assert "permission monitoring" in prompt           # the OnePlus refusal: by hand, protection stays on


def test_the_contributing_guide_walks_a_new_phone_through_to_a_pull_request_that_passes_ci():
    guide = (ROOT / "CONTRIBUTING.md").read_text(encoding="utf-8")

    for step in ("PROMPT.md", "a few days", "tools/probe.py", "phone.json",
                 "python3 tools/gen_tables.py",   # CI fails on stale tables (test_generated_tables_are_up_to_date)
                 "python3 -m pytest", "serial", "git push"):
        assert step in guide, step
    assert "after merging" not in guide


def test_the_oneplus_8t_example_holds_only_what_was_applied_on_the_phone():
    folder = ROOT / "examples" / "oneplus-8t"
    meta = gen_tables.read_phone_json(folder / "phone.json")
    packages = {e.package for e in listfile.load(folder / "debloat.txt").entries}

    assert "KB2003" in meta["models"] and meta["device"] == "OnePlus8T"
    assert len(packages) == 22 and "com.oplus.statistics.rom" in packages
    assert "com.coloros.assistantscreen" not in packages   # refused by the phone, so not applied
    assert "net.oneplus.weather" not in packages           # kept by the person


def test_the_oneplus_list_does_not_offer_what_oxygenos_14_refuses_to_disable():
    entries = {e.package: e for e in listfile.load(ROOT / "lists" / "brands" / "oneplus" / "oxygenos-14.txt").entries}

