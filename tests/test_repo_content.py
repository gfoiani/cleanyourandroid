# gen_tables.py ---------------------------------------------------------------------------------

PHONE = {"phone": "OnePlus 8T", "brand": "OnePlus", "models": ["KB2003", "KB2005"], "device": "OnePlus8T",
         "os": "Android 14, OxygenOS 14", "notes": "Telemetry, HeyTap push, Game Space"}


def make_root(tmp_path):
    marker = "<!-- {0}:start: generated by tools/gen_tables.py -->\nold\n<!-- {0}:end -->\n"
    write(tmp_path / "README.md", "# Title\n" + marker.format("brands"))
    write(tmp_path / "examples" / "README.md", "# Examples\n" + marker.format("phones"))
    write(tmp_path / "examples" / "oneplus-8t" / "phone.json", json.dumps(PHONE))
    write(tmp_path / "examples" / "oneplus-8t" / "debloat.txt", "# == G [safe]\ncom.heytap.mcs\n")
    return tmp_path


def test_gen_tables_writes_the_table_and_brands(tmp_path):
    root = make_root(tmp_path)

    assert gen_tables.main(["--root", str(root)]) == 0

    table = (root / "examples" / "README.md").read_text()
    assert "| `oneplus-8t/` | OnePlus 8T | KB2003, KB2005 | Android 14, OxygenOS 14 |" in table
    assert "OnePlus · 1" in (root / "README.md").read_text()
    assert gen_tables.main(["--check", "--root", str(root)]) == 0


def test_gen_tables_check_fails_when_out_of_date(tmp_path):
    assert gen_tables.main(["--check", "--root", str(make_root(tmp_path))]) == 1


def test_gen_tables_refuses_a_phone_json_without_a_key(tmp_path):
    root = make_root(tmp_path)
    write(root / "examples" / "oneplus-8t" / "phone.json", json.dumps({"phone": "x"}))

    assert gen_tables.main(["--root", str(root)]) == 2
